"""
Shared Cost Function and Residual Analysis for Frequency Assignment.
Evaluates interference penalty ("puntos de interferencia") in Urbania Telecom's network.
"""

from typing import Dict, List, Tuple
import networkx as nx


def compute_interference_cost(graph: nx.Graph, solution: Dict[int, int]) -> float:
    """
    Computes total residual interference cost across the network.
    
    Whenever two adjacent cells (u, v) share the exact same frequency channel
    (solution[u] == solution[v]), mutual interference is incurred with penalty
    equal to edge weight w_uv ('puntos de interferencia').
    
    Args:
        graph: NetworkX graph where edges contain 'weight' attribute.
        solution: Mapping from cell ID (node) to assigned channel (e.g., 0 or 1).
        
    Returns:
        Total interference cost in points.
    """
    total_cost = 0.0
    for u, v, data in graph.edges(data=True):
        weight = data.get("weight", 1.0)
        c_u = solution.get(u)
        c_v = solution.get(v)
        if c_u is not None and c_v is not None and c_u == c_v:
            total_cost += float(weight)
    return round(total_cost, 4)


def compute_node_residuals(graph: nx.Graph, solution: Dict[int, int]) -> Dict[int, float]:
    """
    Calculates the residual interference suffered/generated by each cell individually.
    
    Args:
        graph: NetworkX graph with 'weight' on edges.
        solution: Mapping from cell ID to channel.
        
    Returns:
        Dict mapping each node ID to its total unresolved interference cost.
    """
    residuals = {node: 0.0 for node in graph.nodes()}
    for u, v, data in graph.edges(data=True):
        weight = data.get("weight", 1.0)
        if solution.get(u) == solution.get(v):
            residuals[u] += float(weight)
            residuals[v] += float(weight)
    return residuals


def get_high_residual_subgraph(
    graph: nx.Graph,
    solution: Dict[int, int],
    target_fraction: float = 0.20,
    min_nodes: int = 6,
    max_nodes: int = 40,
) -> Tuple[List[int], nx.Graph, Dict[int, float]]:
    """
    Identifies the subregion of highest residual interference under the candidate solution.
    
    Extracts the top bottleneck cells and calculates boundary field penalties
    exerted by fixed external neighboring cells outside this subregion.
    
    Args:
        graph: Full network graph.
        solution: Current classical baseline assignment.
        target_fraction: Fraction of nodes to select (default 20%).
        min_nodes: Minimum subregion size.
        max_nodes: Maximum subregion size.
        
    Returns:
        Tuple containing:
          - target_nodes: List of selected node IDs.
          - subg: Induced subgraph of target nodes with internal edge weights.
          - boundary_fields: Dict mapping target node u to external bias h_u:
              h_u = 0.5 * sum_{v not in V_target} w_uv * (-1)^(c_v)
              which represents the exact coupling to fixed external neighbors.
    """
    residuals = compute_node_residuals(graph, solution)
    
    # Filter nodes that actually experience positive residual interference
    nodes_with_conflict = [n for n, r in residuals.items() if r > 1e-6]
    if not nodes_with_conflict:
        # All clean or zero conflict, take top degrees
        nodes_sorted = sorted(graph.nodes(), key=lambda n: graph.degree(n, weight="weight"), reverse=True)
    else:
        nodes_sorted = sorted(nodes_with_conflict, key=lambda n: residuals[n], reverse=True)
    
    k = int(len(graph.nodes()) * target_fraction)
    k = max(min_nodes, min(k, max_nodes, len(graph.nodes())))
    
    target_nodes = nodes_sorted[:k]
    target_set = set(target_nodes)
    subg = graph.subgraph(target_nodes).copy()
    
    # Calculate boundary fields from fixed external neighbors
    # For a target node u, an external neighbor v with fixed color c_v in {0, 1}:
    # In spin basis z in {-1, +1} where 0 -> +1, 1 -> -1:
    # Interference term is 0.5 * w_uv * (1 + z_u * z_v)
    # With z_v = 1 if c_v == 0 else -1:
    # Linear contribution to H_C is 0.5 * w_uv * z_v * Z_u
    boundary_fields = {u: 0.0 for u in target_nodes}
    for u in target_nodes:
        for v in graph.neighbors(u):
            if v not in target_set:
                w = graph[u][v].get("weight", 1.0)
                c_v = solution.get(v, 0)
                z_v = 1.0 if c_v == 0 else -1.0
                boundary_fields[u] += 0.5 * float(w) * z_v
                
    return target_nodes, subg, boundary_fields


def get_multiple_residual_subgraphs(
    graph: nx.Graph,
    solution: Dict[int, int],
    threshold: Optional[float] = None,
    threshold_percentile: float = 70.0,
    min_sub_size: int = 4,
    max_sub_size: int = 10,
    max_subgraphs: int = 4,
) -> List[Tuple[List[int], nx.Graph, Dict[int, float], float]]:
    """
    Extracts multiple distinct high-residual subgraphs based on an interference threshold.
    
    Identifies conflicting clusters of cells whose residual interference exceeds
    the threshold, decomposing them into localized subregions for parallel or
    sequential quantum optimization.
    
    Args:
        graph: Full network graph with edge 'weight'.
        solution: Current classical baseline assignment.
        threshold: Explicit interference threshold (in points). If None, calculated
                   from threshold_percentile of positive residuals.
        threshold_percentile: Percentile of positive residuals to use as cutoff (default 70.0).
        min_sub_size: Minimum number of nodes per subgraph (default 4).
        max_sub_size: Maximum number of nodes per subgraph (default 10).
        max_subgraphs: Maximum number of subgraphs to return (default 4).
        
    Returns:
        List of tuples: (target_nodes, induced_subgraph, boundary_fields, density)
    """
    residuals = compute_node_residuals(graph, solution)
    pos_res = [r for r in residuals.values() if r > 1e-5]
    if not pos_res:
        return []
        
    if threshold is None:
        import numpy as np
        threshold = float(np.percentile(pos_res, threshold_percentile))
        
    hot_nodes = [n for n, r in residuals.items() if r >= threshold]
    if len(hot_nodes) < min_sub_size:
        # Fallback to top residual nodes
        hot_nodes = sorted(residuals.keys(), key=lambda n: residuals[n], reverse=True)[:min_sub_size]

    # Cluster hot nodes using modular communities on the induced network topology.
    # This ensures subgraphs are bipolar (contain conflicting nodes of both colors),
    # allowing quantum ansatzes (QAOA^2 and R-QAOA) to explore mutual color swaps.
    sub_hot = graph.subgraph(hot_nodes)
    try:
        from networkx.algorithms.community import greedy_modularity_communities
        components = [list(c) for c in greedy_modularity_communities(sub_hot)]
    except Exception:
        components = [list(c) for c in nx.connected_components(sub_hot)]

    components.sort(key=lambda c: sum(residuals[n] for n in c), reverse=True)
    
    selected_subgraphs = []
    used_nodes = set()

    
    for comp in components:
        comp_nodes = [n for n in comp if n not in used_nodes]
        if len(comp_nodes) < min_sub_size:
            continue
            
        if len(comp_nodes) > max_sub_size:
            comp_nodes = sorted(comp_nodes, key=lambda n: residuals[n], reverse=True)[:max_sub_size]
            
        subg = graph.subgraph(comp_nodes).copy()
        n_c = len(comp_nodes)
        n_e = subg.number_of_edges()
        density = (2.0 * n_e) / (n_c * (n_c - 1)) if n_c > 1 else 0.0
        
        # Calculate boundary fields from external neighbors
        target_set = set(comp_nodes)
        boundary_fields = {u: 0.0 for u in comp_nodes}
        for u in comp_nodes:
            for v in graph.neighbors(u):
                if v not in target_set:
                    w = graph[u][v].get("weight", 1.0)
                    c_v = solution.get(v, 0)
                    z_v = 1.0 if c_v == 0 else -1.0
                    boundary_fields[u] += 0.5 * float(w) * z_v
                    
        selected_subgraphs.append((comp_nodes, subg, boundary_fields, density))
        used_nodes.update(comp_nodes)
        
        if len(selected_subgraphs) >= max_subgraphs:
            break
            
    # If fewer than 2 subgraphs were extracted, take next highest residual nodes
    if len(selected_subgraphs) < 2 and len(hot_nodes) >= min_sub_size:
        remaining = [n for n in sorted(hot_nodes, key=lambda n: residuals[n], reverse=True) if n not in used_nodes]
        while len(remaining) >= min_sub_size and len(selected_subgraphs) < max_subgraphs:
            chunk = remaining[:max_sub_size]
            subg = graph.subgraph(chunk).copy()
            n_c = len(chunk)
            n_e = subg.number_of_edges()
            density = (2.0 * n_e) / (n_c * (n_c - 1)) if n_c > 1 else 0.0
            
            target_set = set(chunk)
            boundary_fields = {u: 0.0 for u in chunk}
            for u in chunk:
                for v in graph.neighbors(u):
                    if v not in target_set:
                        w = graph[u][v].get("weight", 1.0)
                        c_v = solution.get(v, 0)
                        z_v = 1.0 if c_v == 0 else -1.0
                        boundary_fields[u] += 0.5 * float(w) * z_v
                        
            selected_subgraphs.append((chunk, subg, boundary_fields, density))
            used_nodes.update(chunk)
            remaining = remaining[max_sub_size:]
            
    return selected_subgraphs

